const errDupFile = "two inputs convert to the same file %s; convert them separately or give them distinct names"

func typeMeta(kind string) metav1.TypeMeta {
	return metav1.TypeMeta{APIVersion: authentikiov1alpha1.SchemeGroupVersion.String(), Kind: kind}
}

const (
	// metaNamespaceLabel is set by the API server on every namespace.
	metaNamespaceLabel = "kubernetes.io/metadata.name"
	maxSlugLen         = 50
)

// templateGroup is one distinct (template, labels, annotations) tuple.
type templateGroup struct {
	body        string
	labels      map[string]string
	annotations map[string]string
	namespaces  []string
	hash        string
}

// pendingProvider waits for template names, which depend on all inputs.
type pendingProvider struct {
	obj      *authentikiov1alpha1.AuthentikOAuthProvider
	group    string
	filename string
	header   string
	// emptyScopes writes scopes: [] (an explicit empty list is dropped by omitempty).
	emptyScopes bool
}

type builder struct {
	opts          Options
	templates     map[string]*templateGroup
	providers     []pendingProvider
	files         map[string]File
	reports       []objectReport
	templateNames map[string]string
	namespaces    []string // namespaces of the emitted objects, for the adoption-gate hint
}

func (b *builder) addFile(name string, data []byte) error {
	if _, dup := b.files[name]; dup {
		return fmt.Errorf(errDupFile, name)
	}
	b.files[name] = File{Name: name, Data: data}
	return nil
}

func (b *builder) add(a source) error {
	s := a.spec
	rep := objectReport{ref: a.ref()}
	ns := cmp.Or(b.opts.Namespace, a.namespace)
	if !slices.Contains(b.namespaces, ns) {
		b.namespaces = append(b.namespaces, ns)
	}
	slug := cmp.Or(s.Slug, a.name)
	if err := validateSource(a, ns, slug); err != nil {
		return err
	}

	providerName := slug + "-provider" // JeffResc's name for the provider in Authentik.
	resName := slug + b.opts.ProviderSuffix
	secretName := cmp.Or(s.Secret.Name, a.name+"-oauth")
	newSecretName := secretName + b.opts.SecretSuffix

	groupKey, err := b.registerTemplate(a, ns)
	if err != nil {
		return err
	}

	prov, emptyScopes := b.providerSpec(a, providerName, newSecretName, &rep)
	provObj := &authentikiov1alpha1.AuthentikOAuthProvider{
		TypeMeta:   typeMeta("AuthentikOAuthProvider"),
		ObjectMeta: metav1.ObjectMeta{Name: resName, Namespace: ns},
		Spec:       prov,
	}
	provFile := "authentikoauthprovider-" + resName + ".yaml"
	appObj := b.applicationObject(a, ns, slug, resName, &rep)
	appFile := "authentikapplication-" + a.name + ".yaml"
	appData, err := render(appObj, headerFor(a)+b.unmanagedNotice(appObj), dryRunExplicit(b.opts.DryRunAdoption))
	if err != nil {
		return err
	}
	if err := b.addFile(appFile, appData); err != nil {
		return err
	}
	if slices.ContainsFunc(b.providers, func(p pendingProvider) bool { return p.filename == provFile }) {
		return fmt.Errorf(errDupFile, provFile)
	}
	b.providers = append(b.providers,
		pendingProvider{obj: provObj, group: groupKey, filename: provFile, header: headerFor(a),
			emptyScopes: emptyScopes})
	rep.files = []string{provFile, appFile}
	b.describe(a, ns, secretName, newSecretName, &rep)
	b.reports = append(b.reports, rep)
	return nil
}

func headerFor(a source) string {
	return fmt.Sprintf("# Generated by convert-jeffresc from %s.\n", a.ref())
}

func validateSource(a source, ns, slug string) error {
	var errs []string
	if msg := badGroupBindings(a.spec.GroupBindings); msg != "" {
		errs = append(errs, msg)
	}
	if ns == "" {
		errs = append(errs, "no namespace (set metadata.namespace or --namespace)")
	}
	if len(slug) > maxSlugLen {
		errs = append(errs, fmt.Sprintf(
			"slug %q is longer than the %d characters this operator allows", slug, maxSlugLen))
	}
	if l := a.spec.MetaLaunchURL; l != "" && !strings.HasPrefix(l, "http://") && !strings.HasPrefix(l, "https://") {
		errs = append(errs, fmt.Sprintf("metaLaunchUrl %q is not http(s), which this operator requires; "+
			"remove the field to keep the live launch URL on adoption", l))
	}
	if a.spec.Name == "" {
		errs = append(errs, "spec.name is required")
	}
	if len(a.spec.Provider.RedirectURIs) == 0 {
		errs = append(errs, "provider.redirectUris is empty")
	}
	if len(errs) > 0 {
		return fmt.Errorf("%s: %s: %s", a.from, a.ref(), strings.Join(errs, "; "))
	}
	return nil
}

// registerTemplate records the object's template group and returns its key
// ("" when the default Secret keys apply and nothing needs templating).
func (b *builder) registerTemplate(a source, ns string) (string, error) {
	sec := a.spec.Secret
	if sec.Template == "" && len(sec.Labels) == 0 && len(sec.Annotations) == 0 {
		return "", nil
	}
	body := ""
	if sec.Template != "" {
		var err error
		if body, err = convertTemplate(sec.Template, a.kind == kindV1, a.spec.Name, cmp.Or(a.spec.Slug, a.name)); err != nil {
			return "", fmt.Errorf("%s: %s: secret.template: %w", a.from, a.ref(), err)
		}
	}
	labels, annotations := nilIfEmpty(sec.Labels), nilIfEmpty(sec.Annotations)
	canon, err := json.Marshal(struct {
		Body        string            `json:"body"`
		Labels      map[string]string `json:"labels"`
		Annotations map[string]string `json:"annotations"`
	}{body, labels, annotations})
	if err != nil {
		return "", fmt.Errorf("canonicalise template: %w", err)
	}
	sum := sha256.Sum256(canon)
	key := hex.EncodeToString(sum[:])
	g, ok := b.templates[key]
	if !ok {
		g = &templateGroup{body: body, labels: labels, annotations: annotations, hash: key[:8]}
		b.templates[key] = g
	}
	if !slices.Contains(g.namespaces, ns) {
		g.namespaces = append(g.namespaces, ns)
		slices.Sort(g.namespaces)
	}
	return key, nil
}

func (b *builder) providerSpec(
	a source, providerName, secretName string, rep *objectReport,
) (spec authentikiov1alpha1.AuthentikOAuthProviderSpec, emptyScopes bool) {
	p := a.spec.Provider
	spec = authentikiov1alpha1.AuthentikOAuthProviderSpec{
		Name:              providerName,
		AuthorizationFlow: p.AuthorizationFlow,
		InvalidationFlow:  p.InvalidationFlow,
		PropertyMappings:  p.PropertyMappings,
		Secret:            &authentikiov1alpha1.CredentialsSecretSpec{Name: secretName},
		Match:             &authentikiov1alpha1.ProviderMatch{Name: providerName},
		APIManagementSpec: managementSpec(b.opts.DryRunAdoption),
		// A field JeffResc left unset stays unset: JeffResc applied its own
		// default to the live provider, and adoption keeps the live value of
		// every field the spec does not set.
		ClientType:             authentikiov1alpha1.OAuthClientType(p.ClientType),
		AccessCodeValidity:     p.AccessCodeValidity,
		AccessTokenValidity:    p.AccessTokenValidity,
		RefreshTokenValidity:   p.RefreshTokenValidity,
		SubMode:                authentikiov1alpha1.OAuthSubMode(p.SubMode),
		IssuerMode:             authentikiov1alpha1.OAuthIssuerMode(p.IssuerMode),
		IncludeClaimsInIDToken: p.IncludeClaimsInIDToken,
	}
	if p.SigningKey != nil { // an explicit "" is omitted: the live signing key is kept.
		spec.SigningKey = *p.SigningKey
	}
	spec.GrantTypes = grantTypes(p.GrantTypes, rep)
	if b.opts.AuthentikRef != "" {
		spec.AuthentikRef = &authentikiov1alpha1.AuthentikRef{Name: b.opts.AuthentikRef}
	}
	for _, u := range p.RedirectURIs {
		spec.RedirectURIs = append(spec.RedirectURIs, authentikiov1alpha1.RedirectURI{URL: u})
	}
	if p.Scopes != nil {
		switch {
		case len(*p.Scopes) > 0:
			spec.Scopes = *p.Scopes
		case len(p.PropertyMappings) > 0:
			emptyScopes = true
			rep.notes = append(rep.notes, "provider.scopes is explicitly empty in JeffResc: emitted as scopes: [] "+
				"(the provider keeps only the propertyMappings)")
		default:
			rep.notes = append(rep.notes, "provider.scopes is explicitly empty in JeffResc with no propertyMappings, "+
				"which leaves the live property mappings alone: scopes is left unset, so adoption keeps them too")
		}
	}
	return spec, emptyScopes
}

// grantTypes is always written, because adoption keeps the live value of an
// unset field and a provider created by JeffResc v0.2.6 or older has none,
// which Authentik 2026.5+ rejects every login for. JeffResc v0.2.7+ sends
// spec.provider.grantTypes and treats an empty list as its default pair
// (internal/authentik/provider.go buildGrantTypes), so the converter does the
// same: copy the list without duplicates (the CRD is a set), else the pair.
func grantTypes(in []string, rep *objectReport) []authentikiov1alpha1.OAuthGrantType {
	var out []authentikiov1alpha1.OAuthGrantType
	for _, g := range in {
		if t := authentikiov1alpha1.OAuthGrantType(g); !slices.Contains(out, t) {
			out = append(out, t)
		}
	}
	if len(out) > 0 {
		rep.notes = append(rep.notes, "provider.grantTypes copied from JeffResc: "+showGrantTypes(out))
		return out
	}
	out = []authentikiov1alpha1.OAuthGrantType{"authorization_code", "refresh_token"}
	rep.notes = append(rep.notes, "provider.grantTypes defaulted to "+showGrantTypes(out)+
		" (unset or empty in JeffResc, which treats both as this pair); if the live provider has more, the dry run "+
		"shows them narrowed")
	return out
}

func showGrantTypes(g []authentikiov1alpha1.OAuthGrantType) string {
	s := make([]string, len(g))
	for i, t := range g {
		s[i] = string(t)
	}
	return "[" + strings.Join(s, ", ") + "]"
}

// Limits of spec.access.groups in the CRD.
const (
	maxAccessGroups = 64
	maxGroupNameLen = 255
)

// badGroupBindings says why groupBindings cannot become spec.access.groups, or
// "" when they can: the CRD takes 1 to 64 names of 1 to 255 characters.
func badGroupBindings(groupBindings []string) string {
	distinct := slices.Clone(groupBindings)
	slices.Sort(distinct)
	distinct = slices.Compact(distinct)
	for _, g := range distinct {
		if g == "" || utf8.RuneCountInString(g) > maxGroupNameLen {
			return fmt.Sprintf("groupBindings has an entry (%s) that is empty or longer than the %d characters "+
				"this operator allows", strconv.Quote(g), maxGroupNameLen)
		}
	}
	if len(distinct) > maxAccessGroups {
		return fmt.Sprintf("groupBindings lists %d groups; this operator allows %d in spec.access.groups",
			len(distinct), maxAccessGroups)
	}
	return ""
}

// accessFor converts JeffResc groupBindings to spec.access: Groups with each
// name once, in input order, or Unmanaged when there are none. A name listed
// twice is reported.
func accessFor(groupBindings []string, rep *objectReport) *authentikiov1alpha1.ApplicationAccess {
	var groups []string
	for _, g := range groupBindings {
		if slices.Contains(groups, g) {
			rep.notes = append(rep.notes, fmt.Sprintf("groupBindings lists %q more than once; kept once", g))
			continue
		}
		groups = append(groups, g)
	}
	if len(groups) == 0 {
		return &authentikiov1alpha1.ApplicationAccess{Type: authentikiov1alpha1.AccessTypeUnmanaged}
	}
	return &authentikiov1alpha1.ApplicationAccess{Type: authentikiov1alpha1.AccessTypeGroups, Groups: groups}
}

// unmanagedNotice is the header line of an application whose spec.access is
// Unmanaged: the bindings JeffResc may have created cannot be seen offline.
func (b *builder) unmanagedNotice(app *authentikiov1alpha1.AuthentikApplication) string {
	if app.Spec.Access.Type != authentikiov1alpha1.AccessTypeUnmanaged {
		return ""
	}
	const prefix = "# spec.access is Unmanaged: this application's live bindings are unknown offline; "
	if b.opts.DryRunAdoption {
		return prefix + "the adoption dry run lists them.\n"
	}
	return prefix + "status.access.bindings lists them once applied.\n"
}

func (b *builder) applicationObject(a source, ns, slug, providerRes string,
	rep *objectReport) *authentikiov1alpha1.AuthentikApplication {
	s := a.spec
	access := accessFor(s.GroupBindings, rep)
	mode := authentikiov1alpha1.PolicyEngineMode(s.PolicyEngineMode)
	if mode == authentikiov1alpha1.PolicyEngineMode("all") && len(access.Groups) > 1 {
		// The CRD refuses all with several groups. Adoption keeps the live
		// value, so the behaviour is unchanged and the application reports it.
		mode = ""
		rep.notes = append(rep.notes, "policyEngineMode all with several groupBindings left unset: the live value is "+
			"kept and reported as AccessNarrowed")
	}
	spec := authentikiov1alpha1.AuthentikApplicationSpec{
		Name:              s.Name,
		Slug:              slug,
		ProviderRef:       &authentikiov1alpha1.ProviderRef{Kind: authentikiov1alpha1.ProviderKindOAuth, Name: providerRes},
		Access:            access,
		Group:             s.Group,
		PolicyEngineMode:  mode,
		MetaLaunchURL:     s.MetaLaunchURL,
		MetaDescription:   s.MetaDescription,
		MetaPublisher:     s.MetaPublisher,
		OpenInNewTab:      s.OpenInNewTab,
		APIManagementSpec: managementSpec(b.opts.DryRunAdoption),
	}
	if b.opts.AuthentikRef != "" {
		spec.AuthentikRef = &authentikiov1alpha1.AuthentikRef{Name: b.opts.AuthentikRef}
	}
	return &authentikiov1alpha1.AuthentikApplication{
		TypeMeta:   typeMeta("AuthentikApplication"),
		ObjectMeta: metav1.ObjectMeta{Name: a.name, Namespace: ns},
		Spec:       spec,
	}
}

// finish names the templates, links providers to them and serialises.
func (b *builder) finish() error {
	keys := make([]string, 0, len(b.templates))
	for k := range b.templates {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	names := map[string]string{}
	for _, k := range keys {
		g := b.templates[k]
		name := "jeffresc-" + g.hash
		switch {
		case b.opts.TemplateName != "" && len(keys) == 1:
			name = b.opts.TemplateName
		case b.opts.TemplateName != "":
			name = b.opts.TemplateName + "-" + g.hash
		}
		if errs := validation.IsDNS1123Subdomain(name); len(errs) > 0 {
			return fmt.Errorf("template name %q: %s", name, strings.Join(errs, "; "))
		}
		names[k] = name
		obj := &authentikiov1alpha1.AuthentikCredentialsTemplate{
			TypeMeta:   typeMeta("AuthentikCredentialsTemplate"),
			ObjectMeta: metav1.ObjectMeta{Name: name},
			Spec: authentikiov1alpha1.AuthentikCredentialsTemplateSpec{
				Template: g.body, Labels: g.labels, Annotations: g.annotations,
				NamespaceSelector: metav1.LabelSelector{MatchExpressions: []metav1.LabelSelectorRequirement{{
					Key: metaNamespaceLabel, Operator: metav1.LabelSelectorOpIn, Values: g.namespaces,
				}}},
			},
		}
		data, err := render(obj, "# Cluster-scoped and administrator-owned: a platform admin applies this.\n")
		if err != nil {
			return err
		}
		if err := b.addFile("authentikcredentialstemplate-"+name+".yaml", data); err != nil {
			return err
		}
	}
	var errs []error
	for _, p := range b.providers {
		if p.group != "" {
			p.obj.Spec.Secret.TemplateRef = &authentikiov1alpha1.CredentialsTemplateRef{Name: names[p.group]}
		}
		patches := []func(map[string]any){dryRunExplicit(b.opts.DryRunAdoption)}
		if p.emptyScopes {
			// [0]string{} marshals as [], where a nil slice would be null.
			patches = append(patches, func(spec map[string]any) { spec["scopes"] = [0]string{} })
		}
		data, err := render(p.obj, p.header, patches...)
		if err == nil {
			err = b.addFile(p.filename, data)
		}
		errs = append(errs, err)
	}
	b.templateNames = names
	return errors.Join(errs...)
}

// managementSpec is what every converted object carries: it adopts the object
// JeffResc created and, when deleted, leaves it in Authentik.
func managementSpec(dryRun bool) authentikiov1alpha1.APIManagementSpec {
	return authentikiov1alpha1.APIManagementSpec{
		ManagementPolicy: authentikiov1alpha1.ManagementPolicyAdopt,
		DryRun:           dryRun,
		DeletionPolicy:   authentikiov1alpha1.DeletionPolicyRetain,
	}
}

// dryRunExplicit writes spec.dryRun out even when false, so it is easy to flip.
func dryRunExplicit(dryRun bool) func(map[string]any) {
	return func(spec map[string]any) { spec["dryRun"] = dryRun }
}

// render marshals obj without status or timestamps, then applies patches to
// the spec map.
func render(obj any, header string, patches ...func(spec map[string]any)) ([]byte, error) {
	raw, err := json.Marshal(obj)
	if err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	var m map[string]any
	if err := json.Unmarshal(raw, &m); err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	delete(m, "status")
	if meta, ok := m["metadata"].(map[string]any); ok {
		delete(meta, "creationTimestamp")
	}
	if spec, ok := m["spec"].(map[string]any); ok {
		for _, patch := range patches {
			patch(spec)
		}
	}
	out, err := yaml.Marshal(m)
	if err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	return append([]byte(header), out...), nil
}

func nilIfEmpty(m map[string]string) map[string]string {
	if len(m) == 0 {
		return nil
	}
	return m
}
